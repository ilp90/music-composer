import { randomUUID } from 'node:crypto';
import { exportJWK, generateKeyPair } from 'jose';
import { ulid } from 'ulid';
import { afterEach, describe, expect, it, vi } from 'vitest';
import {
  createTokenService,
  generateRefreshToken,
  loadSigningKey,
  parseRefreshToken,
} from './tokens';

afterEach(() => {
  vi.useRealTimers();
});

describe('access tokens', () => {
  it('round-trips the user id', async () => {
    const tokens = createTokenService(await loadSigningKey(undefined), 'test', 900);
    const userId = ulid();

    expect(await tokens.verifyAccessToken(await tokens.signAccessToken(userId))).toBe(userId);
  });

  it('loads a private JWK (as generated by keys:generate) and puts its kid in the header', async () => {
    const { privateKey } = await generateKeyPair('ES256', { extractable: true });
    const kid = randomUUID();
    const key = await loadSigningKey(JSON.stringify({ ...(await exportJWK(privateKey)), kid }));
    const tokens = createTokenService(key, 'test', 900);

    const token = await tokens.signAccessToken('user-1');
    const header = JSON.parse(Buffer.from(token.split('.')[0]!, 'base64url').toString());

    expect(key.ephemeral).toBe(false);
    expect(header).toMatchObject({ alg: 'ES256', kid });
    expect(await tokens.verifyAccessToken(token)).toBe('user-1');
  });

  it('rejects a public-only JWK', async () => {
    const { publicKey } = await generateKeyPair('ES256', { extractable: true });
    const jwk = JSON.stringify({ ...(await exportJWK(publicKey)), kid: 'k' });

    await expect(loadSigningKey(jwk)).rejects.toThrow(/private EC JWK/);
  });

  it('rejects expired tokens', async () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    const tokens = createTokenService(await loadSigningKey(undefined), 'test', 60);
    const token = await tokens.signAccessToken('user-1');

    vi.setSystemTime(Date.now() + 61_000);

    await expect(tokens.verifyAccessToken(token)).rejects.toThrow('Invalid access token');
  });

  it('rejects tokens signed by another key, for another issuer, or tampered with', async () => {
    const tokens = createTokenService(await loadSigningKey(undefined), 'test', 900);
    const otherKey = createTokenService(await loadSigningKey(undefined), 'test', 900);
    const otherIssuer = createTokenService(await loadSigningKey(undefined), 'someone-else', 900);
    const good = await tokens.signAccessToken('user-1');
    const [header, , signature] = good.split('.');
    const forgedPayload = Buffer.from(JSON.stringify({ sub: 'admin' })).toString('base64url');

    await expect(
      tokens.verifyAccessToken(await otherKey.signAccessToken('user-1')),
    ).rejects.toThrow();
    await expect(
      tokens.verifyAccessToken(await otherIssuer.signAccessToken('user-1')),
    ).rejects.toThrow();
    await expect(
      tokens.verifyAccessToken(`${header}.${forgedPayload}.${signature}`),
    ).rejects.toThrow();
    await expect(tokens.verifyAccessToken('not-a-jwt')).rejects.toThrow();
  });
});

describe('refresh tokens', () => {
  it('parses back to the user id and the stored hash', () => {
    const userId = ulid();
    const { token, hash } = generateRefreshToken(userId);

    expect(parseRefreshToken(token)).toEqual({ userId, hash });
    expect(hash).not.toBe(token.split('.')[1]);
  });

  it('generates unique secrets', () => {
    const userId = ulid();
    expect(generateRefreshToken(userId).token).not.toBe(generateRefreshToken(userId).token);
  });

  it('rejects malformed tokens', () => {
    const { token } = generateRefreshToken(ulid());

    expect(parseRefreshToken(undefined)).toBeUndefined();
    expect(parseRefreshToken('')).toBeUndefined();
    expect(parseRefreshToken('nodot')).toBeUndefined();
    expect(parseRefreshToken(`${token}x`)).toBeUndefined();
    expect(parseRefreshToken(`not-a-ulid.${token.split('.')[1]}`)).toBeUndefined();
  });
});
